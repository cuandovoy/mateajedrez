CREATE TABLE IF NOT EXISTS purchase_orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  supplier_id UUID NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
  branch_id UUID NOT NULL REFERENCES branches(id) ON DELETE RESTRICT,
  po_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  status VARCHAR(30) NOT NULL DEFAULT 'draft' CHECK (
    status IN ('draft', 'submitted', 'partially_received', 'received', 'cancelled')
  ),
  currency_code CHAR(3) NOT NULL DEFAULT 'UYU',
  ordered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expected_at TIMESTAMPTZ,
  received_at TIMESTAMPTZ,
  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
  tax_total NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount_total NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL DEFAULT 0,
  notes TEXT,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  approved_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (organization_id, po_number)
);

CREATE INDEX IF NOT EXISTS idx_purchase_orders_org_created_at ON purchase_orders(organization_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_org_status ON purchase_orders(organization_id, status);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_org_supplier ON purchase_orders(organization_id, supplier_id);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_org_branch ON purchase_orders(organization_id, branch_id);

