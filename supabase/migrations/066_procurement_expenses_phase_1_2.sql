CREATE OR REPLACE FUNCTION sync_supplier_invoice_payment_totals(p_supplier_invoice_id UUID)
RETURNS VOID AS $$
DECLARE
  v_paid NUMERIC(12,2);
BEGIN
  SELECT COALESCE(SUM(amount), 0)::NUMERIC(12,2)
  INTO v_paid
  FROM supplier_payments
  WHERE supplier_invoice_id = p_supplier_invoice_id
    AND status = 'posted';

  UPDATE supplier_invoices
  SET
    paid_amount = v_paid,
    outstanding_amount = GREATEST(total_amount - v_paid, 0),
    status = CASE
      WHEN status = 'cancelled' THEN 'cancelled'
      WHEN v_paid <= 0 AND status = 'draft' THEN 'draft'
      WHEN v_paid <= 0 THEN 'issued'
      WHEN v_paid >= total_amount THEN 'paid'
      ELSE 'partially_paid'
    END,
    updated_at = NOW()
  WHERE id = p_supplier_invoice_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

