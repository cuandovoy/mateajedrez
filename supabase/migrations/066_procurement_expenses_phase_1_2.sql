CREATE OR REPLACE FUNCTION trg_expense_ledger_on_supplier_payment()
RETURNS TRIGGER AS $$
DECLARE
  v_invoice supplier_invoices%ROWTYPE;
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.status = 'posted' THEN
      SELECT * INTO v_invoice FROM supplier_invoices WHERE id = NEW.supplier_invoice_id;

      INSERT INTO expense_ledger (
        organization_id,
        branch_id,
        supplier_id,
        entry_kind,
        event_type,
        source_table,
        source_id,
        occurred_at,
        currency_code,
        gross_amount,
        tax_amount,
        discount_amount,
        net_amount,
        status,
        metadata,
        created_by
      )
      VALUES (
        NEW.organization_id,
        NEW.branch_id,
        NEW.supplier_id,
        'cash',
        'payment',
        'supplier_payments',
        NEW.id,
        NEW.payment_date,
        COALESCE(v_invoice.currency_code, 'UYU'),
        NEW.amount,
        0,
        0,
        NEW.amount,
        'posted',
        jsonb_build_object(
          'supplier_invoice_id', NEW.supplier_invoice_id,
          'payment_method', NEW.payment_method,
          'reference_number', NEW.reference_number
        ),
        NEW.created_by
      )
      ON CONFLICT DO NOTHING;
    END IF;

    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    -- Reversal creates a compensating cash entry
    IF OLD.status = 'posted' AND NEW.status = 'reversed' THEN
      SELECT * INTO v_invoice FROM supplier_invoices WHERE id = NEW.supplier_invoice_id;

      INSERT INTO expense_ledger (
        organization_id,
        branch_id,
        supplier_id,
        entry_kind,
        event_type,
        source_table,
        source_id,
        occurred_at,
        currency_code,
        gross_amount,
        tax_amount,
        discount_amount,
        net_amount,
        status,
        metadata,
        created_by
      )
      VALUES (
        NEW.organization_id,
        NEW.branch_id,
        NEW.supplier_id,
        'cash',
        'payment_reversal',
        'supplier_payments',
        NEW.id,
        COALESCE(NEW.reversed_at, NOW()),
        COALESCE(v_invoice.currency_code, 'UYU'),
        -NEW.amount,
        0,
        0,
        -NEW.amount,
        'posted',
        jsonb_build_object(
          'supplier_invoice_id', NEW.supplier_invoice_id,
          'reversal_of_payment_id', NEW.id,
          'payment_method', NEW.payment_method
        ),
        COALESCE(NEW.reversed_by, NEW.created_by)
      )
      ON CONFLICT DO NOTHING;
    END IF;

    RETURN NEW;
  END IF;

  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS expense_ledger_on_supplier_payment ON supplier_payments;
CREATE TRIGGER expense_ledger_on_supplier_payment
  AFTER INSERT OR UPDATE ON supplier_payments
  FOR EACH ROW EXECUTE FUNCTION trg_expense_ledger_on_supplier_payment();

