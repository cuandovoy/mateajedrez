CREATE OR REPLACE FUNCTION recalculate_purchase_order_totals(p_purchase_order_id UUID)
RETURNS VOID AS $$
BEGIN
  UPDATE purchase_orders po
  SET
    subtotal = COALESCE(calc.subtotal, 0),
    tax_total = COALESCE(calc.tax_total, 0),
    discount_total = COALESCE(calc.discount_total, 0),
    total = COALESCE(calc.subtotal, 0) + COALESCE(calc.tax_total, 0) - COALESCE(calc.discount_total, 0),
    updated_at = NOW()
  FROM (
    SELECT
      purchase_order_id,
      SUM(quantity_ordered * unit_cost)::NUMERIC(12,2) AS subtotal,
      SUM(tax_amount)::NUMERIC(12,2) AS tax_total,
      SUM(discount_amount)::NUMERIC(12,2) AS discount_total
    FROM purchase_order_items
    WHERE purchase_order_id = p_purchase_order_id
    GROUP BY purchase_order_id
  ) calc
  WHERE po.id = calc.purchase_order_id;

  UPDATE purchase_orders
  SET subtotal = 0, tax_total = 0, discount_total = 0, total = 0, updated_at = NOW()
  WHERE id = p_purchase_order_id
    AND NOT EXISTS (SELECT 1 FROM purchase_order_items WHERE purchase_order_id = p_purchase_order_id);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION trg_recalculate_purchase_order_totals()
RETURNS TRIGGER AS $$
DECLARE
  v_purchase_order_id UUID;
BEGIN
  v_purchase_order_id := COALESCE(NEW.purchase_order_id, OLD.purchase_order_id);
  PERFORM recalculate_purchase_order_totals(v_purchase_order_id);
  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS recalculate_purchase_order_totals_on_items ON purchase_order_items;
CREATE TRIGGER recalculate_purchase_order_totals_on_items
  AFTER INSERT OR UPDATE OR DELETE ON purchase_order_items
  FOR EACH ROW EXECUTE FUNCTION trg_recalculate_purchase_order_totals();

