CREATE OR REPLACE FUNCTION post_goods_receipt(p_goods_receipt_id UUID)
RETURNS UUID AS $$
DECLARE
  v_receipt goods_receipts%ROWTYPE;
  v_item RECORD;
  v_branch_inventory_id UUID;
  v_previous_stock INTEGER;
  v_new_stock INTEGER;
BEGIN
  SELECT *
  INTO v_receipt
  FROM goods_receipts
  WHERE id = p_goods_receipt_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'goods_receipt % not found', p_goods_receipt_id;
  END IF;

  IF v_receipt.status <> 'draft' THEN
    RAISE EXCEPTION 'goods_receipt % is not in draft status', p_goods_receipt_id;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM goods_receipt_items WHERE goods_receipt_id = p_goods_receipt_id) THEN
    RAISE EXCEPTION 'goods_receipt % has no items', p_goods_receipt_id;
  END IF;

  FOR v_item IN
    SELECT *
    FROM goods_receipt_items
    WHERE goods_receipt_id = p_goods_receipt_id
  LOOP
    IF v_item.variant_id IS NOT NULL THEN
      INSERT INTO branch_inventory (branch_id, product_id, variant_id, stock, min_stock, low_stock_threshold)
      VALUES (v_receipt.branch_id, NULL, v_item.variant_id, 0, 0, 10)
      ON CONFLICT (branch_id, variant_id) WHERE variant_id IS NOT NULL DO NOTHING;

      SELECT id, stock INTO v_branch_inventory_id, v_previous_stock
      FROM branch_inventory
      WHERE branch_id = v_receipt.branch_id
        AND variant_id = v_item.variant_id
        AND product_id IS NULL
      FOR UPDATE;
    ELSE
      INSERT INTO branch_inventory (branch_id, product_id, variant_id, stock, min_stock, low_stock_threshold)
      VALUES (v_receipt.branch_id, v_item.product_id, NULL, 0, 0, 10)
      ON CONFLICT (branch_id, product_id) WHERE product_id IS NOT NULL DO NOTHING;

      SELECT id, stock INTO v_branch_inventory_id, v_previous_stock
      FROM branch_inventory
      WHERE branch_id = v_receipt.branch_id
        AND product_id = v_item.product_id
        AND variant_id IS NULL
      FOR UPDATE;
    END IF;

    IF v_branch_inventory_id IS NULL THEN
      RAISE EXCEPTION 'could not resolve branch_inventory entry for receipt item %', v_item.id;
    END IF;

    v_new_stock := COALESCE(v_previous_stock, 0) + v_item.quantity_received;

    UPDATE branch_inventory
    SET stock = v_new_stock,
        updated_at = NOW()
    WHERE id = v_branch_inventory_id;

    PERFORM create_inventory_movement(
      v_branch_inventory_id,
      'receipt',
      v_item.quantity_received,
      COALESCE(v_previous_stock, 0),
      v_new_stock,
      p_goods_receipt_id,
      'goods_receipt',
      COALESCE(v_item.notes, v_receipt.notes),
      v_receipt.supplier_id
    );
  END LOOP;

  UPDATE goods_receipts
  SET status = 'posted',
      posted_by = auth.uid(),
      posted_at = NOW(),
      updated_at = NOW()
  WHERE id = p_goods_receipt_id;

  -- Update PO progress if the receipt is linked to a PO
  IF v_receipt.purchase_order_id IS NOT NULL THEN
    UPDATE purchase_order_items poi
    SET quantity_received = COALESCE(src.qty_received, 0)
    FROM (
      SELECT
        gri.purchase_order_item_id,
        SUM(gri.quantity_received)::INTEGER AS qty_received
      FROM goods_receipt_items gri
      JOIN goods_receipts gr ON gr.id = gri.goods_receipt_id
      WHERE gr.status = 'posted'
        AND gri.purchase_order_item_id IS NOT NULL
      GROUP BY gri.purchase_order_item_id
    ) src
    WHERE poi.id = src.purchase_order_item_id
      AND poi.purchase_order_id = v_receipt.purchase_order_id;

    UPDATE purchase_orders po
    SET
      status = CASE
        WHEN EXISTS (
          SELECT 1 FROM purchase_order_items poi
          WHERE poi.purchase_order_id = po.id
            AND poi.quantity_received < poi.quantity_ordered
        ) THEN 'partially_received'
        ELSE 'received'
      END,
      received_at = CASE
        WHEN NOT EXISTS (
          SELECT 1 FROM purchase_order_items poi
          WHERE poi.purchase_order_id = po.id
            AND poi.quantity_received < poi.quantity_ordered
        ) THEN NOW()
        ELSE po.received_at
      END,
      updated_at = NOW()
    WHERE po.id = v_receipt.purchase_order_id
      AND po.status <> 'cancelled';
  END IF;

  RETURN p_goods_receipt_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION post_supplier_invoice(p_supplier_invoice_id UUID)
RETURNS UUID AS $$
DECLARE
  v_invoice supplier_invoices%ROWTYPE;
BEGIN
  SELECT *
  INTO v_invoice
  FROM supplier_invoices
  WHERE id = p_supplier_invoice_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'supplier_invoice % not found', p_supplier_invoice_id;
  END IF;

  IF v_invoice.status = 'cancelled' THEN
    RAISE EXCEPTION 'supplier_invoice % is cancelled', p_supplier_invoice_id;
  END IF;

  IF v_invoice.status = 'draft' THEN
    UPDATE supplier_invoices
    SET status = 'issued',
        paid_amount = COALESCE(paid_amount, 0),
        outstanding_amount = GREATEST(total_amount - COALESCE(paid_amount, 0), 0),
        updated_at = NOW()
    WHERE id = p_supplier_invoice_id;
  END IF;

  INSERT INTO expense_ledger (
    organization_id,
    branch_id,
    supplier_id,
    entry_kind,
    event_type,
    source_table,
    source_id,
    occurred_at,
    currency_code,
    gross_amount,
    tax_amount,
    discount_amount,
    net_amount,
    status,
    metadata,
    created_by
  )
  VALUES (
    v_invoice.organization_id,
    v_invoice.branch_id,
    v_invoice.supplier_id,
    'accrual',
    'invoice',
    'supplier_invoices',
    v_invoice.id,
    NOW(),
    v_invoice.currency_code,
    v_invoice.subtotal,
    v_invoice.tax_total,
    v_invoice.discount_total,
    v_invoice.total_amount,
    'posted',
    jsonb_build_object('invoice_number', v_invoice.invoice_number),
    auth.uid()
  )
  ON CONFLICT DO NOTHING;

  RETURN p_supplier_invoice_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION register_supplier_payment(
  p_supplier_invoice_id UUID,
  p_amount NUMERIC(12,2),
  p_payment_method VARCHAR(50),
  p_payment_date TIMESTAMPTZ DEFAULT NOW(),
  p_reference_number VARCHAR(120) DEFAULT NULL,
  p_notes TEXT DEFAULT NULL
)
RETURNS UUID AS $$
DECLARE
  v_invoice supplier_invoices%ROWTYPE;
  v_payment_id UUID;
BEGIN
  IF p_amount <= 0 THEN
    RAISE EXCEPTION 'payment amount must be greater than 0';
  END IF;

  SELECT *
  INTO v_invoice
  FROM supplier_invoices
  WHERE id = p_supplier_invoice_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'supplier_invoice % not found', p_supplier_invoice_id;
  END IF;

  IF v_invoice.status = 'cancelled' THEN
    RAISE EXCEPTION 'cannot pay cancelled invoice %', p_supplier_invoice_id;
  END IF;

  IF v_invoice.outstanding_amount <= 0 THEN
    RAISE EXCEPTION 'invoice % has no outstanding amount', p_supplier_invoice_id;
  END IF;

  IF p_amount > v_invoice.outstanding_amount THEN
    RAISE EXCEPTION 'payment amount (%) exceeds outstanding amount (%)', p_amount, v_invoice.outstanding_amount;
  END IF;

  INSERT INTO supplier_payments (
    organization_id,
    supplier_invoice_id,
    supplier_id,
    branch_id,
    payment_method,
    payment_date,
    amount,
    status,
    reference_number,
    notes,
    created_by
  )
  VALUES (
    v_invoice.organization_id,
    v_invoice.id,
    v_invoice.supplier_id,
    v_invoice.branch_id,
    p_payment_method,
    COALESCE(p_payment_date, NOW()),
    p_amount,
    'posted',
    p_reference_number,
    p_notes,
    auth.uid()
  )
  RETURNING id INTO v_payment_id;

  RETURN v_payment_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

